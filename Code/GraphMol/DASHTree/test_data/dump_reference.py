"""Dump reference values from the DASH-tree python package for the tests.

Writes ``dash_ref_mols.sdf`` -- molecules with explicit hydrogens, so
their atom order is fixed -- and ``dash_ref_values.txt`` holding, one
whitespace-separated line per atom:

    molIdx atomIdx rawResult stdUsed matchDepth qNone qSymmetric qStdWeighted

Values are printed with ``repr`` precision so the C++ test can compare the
table lookups exactly rather than to a tolerance.

Needs the DASH-tree package (``serenityff``) importable and its default tree
present. Molecules are taken from a SMILES file; the default is the ChEMBL
extract that ships with RDKit, so this needs no data of its own.

Usage:
    python dump_reference.py <out_dir> [smiles-file] [nMols]
"""

import gzip
import os
import sys

from rdkit import Chem, RDLogger

RDLogger.DisableLog("rdApp.*")


def loadSmiles(path, limit):
  opener = gzip.open if path.endswith(".gz") else open
  out = []
  with opener(path, "rt") as f:
    for line in f:
      parts = line.split()
      if parts:
        out.append(parts[0])
      if len(out) >= limit:
        break
  return out


def main():
  outDir = sys.argv[1]
  rdbase = os.environ.get("RDBASE", "")
  smilesPath = (sys.argv[2] if len(sys.argv) > 2 else os.path.join(rdbase, "Regress", "Data",
                                                                   "chembl_20_chiral.smi.gz"))
  nMols = int(sys.argv[3]) if len(sys.argv) > 3 else 100

  from serenityff.charge.tree.atom_features import AtomFeatures
  from serenityff.charge.tree.dash_tree import DASHTree

  def supported(mol):
    for atom in mol.GetAtoms():
      tup = AtomFeatures.return_atom_feature_tuple_from_molecule(mol, atom.GetIdx())
      if tup not in AtomFeatures.afTuple_2_afKey:
        return False
    return True

  tree = DASHTree(verbose=False)

  mols = []
  for smiles in loadSmiles(smilesPath, 20 * nMols):
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
      continue
    mol = Chem.AddHs(mol)
    if not supported(mol):
      continue
    try:
      paths = tree._get_allAtoms_nodePaths(mol)
      rows = []
      for atomIdx, path in enumerate(paths):
        raw = float(tree.get_property_noNAN(matched_node_path=path, property_name="result"))
        dev = float(tree.get_property_noNAN(matched_node_path=path, property_name="std"))
        rows.append((atomIdx, raw, dev if dev > 0 else 0.1, len(path) - 1))
      charges = {
        name: tree.get_molecules_partial_charges(mol, norm_method=name,
                                                 nodePathList=paths)["charges"]
        for name in ("none", "symmetric", "std_weighted")
      }
    except Exception:
      # the python implementation walks its node path past the end and
      # dies inside pandas for atoms whose feature class holds no data
      continue
    mols.append((mol, rows, charges))
    if len(mols) >= nMols:
      break

  os.makedirs(outDir, exist_ok=True)
  sdfPath = os.path.join(outDir, "dash_ref_mols.sdf")
  writer = Chem.SDWriter(sdfPath)
  for i, (mol, _, _) in enumerate(mols):
    mol.SetProp("_Name", f"dash_ref_{i}")
    writer.write(mol)
  writer.close()

  valuesPath = os.path.join(outDir, "dash_ref_values.txt")
  nAtoms = 0
  with open(valuesPath, "w") as f:
    f.write("# molIdx atomIdx rawResult stdUsed matchDepth qNone "
            "qSymmetric qStdWeighted\n")
    f.write("# generated by Code/GraphMol/DASHTree/test_data/dump_reference.py "
            "from the DASH-tree python package\n")
    for molIdx, (mol, rows, charges) in enumerate(mols):
      for atomIdx, raw, dev, depth in rows:
        f.write(f"{molIdx} {atomIdx} {raw!r} {dev!r} {depth} "
                f"{charges['none'][atomIdx]!r} "
                f"{charges['symmetric'][atomIdx]!r} "
                f"{charges['std_weighted'][atomIdx]!r}\n")
        nAtoms += 1

  print(f"wrote {sdfPath} ({len(mols)} molecules, "
        f"{os.path.getsize(sdfPath)/1e6:.2f} MB)")
  print(f"wrote {valuesPath} ({nAtoms} atoms, "
        f"{os.path.getsize(valuesPath)/1e6:.2f} MB)")


if __name__ == "__main__":
  main()
